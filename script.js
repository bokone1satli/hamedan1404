// ============ وضعیت ============
var sentCount = 0;
var SENT_KEY = "report_sent_count_hamedan1404";

// ============ توابع ============

function buildMailtoLink() {
  var subjectEncoded = encodeURIComponent(CONFIG.subject);
  var bodyEncoded = encodeURIComponent(CONFIG.body);
  return "mailto:" + CONFIG.recipient + "?subject=" + subjectEncoded + "&body=" + bodyEncoded;
}

function showPreview() {
  var preview = document.getElementById("emailPreview");
  if (preview) {
    preview.textContent = "Subject: " + CONFIG.subject + "\n\n" + CONFIG.body;
  }
}

function updateCounter() {
  var counter = document.getElementById("counter");
  if (!counter) return;
  if (sentCount === 0) {
    counter.textContent = "آماده برای ارسال";
  } else {
    counter.textContent = "✅ " + sentCount + " گزارش ارسال شده";
  }
}

// کپی متن کامل
function copyFullText() {
  var fullText = "To: " + CONFIG.recipient + "\nSubject: " + CONFIG.subject + "\n\n" + CONFIG.body;

  if (navigator.clipboard && navigator.clipboard.writeText) {
    navigator.clipboard.writeText(fullText).then(function() {
      showToast("✅ متن کامل گزارش کپی شد!");
    }).catch(function() {
      fallbackCopy(fullText);
    });
  } else {
    fallbackCopy(fullText);
  }
}

// کپی فقط Subject
function copySubject() {
  if (navigator.clipboard && navigator.clipboard.writeText) {
    navigator.clipboard.writeText(CONFIG.subject).then(function() {
      showToast("✅ موضوع (Subject) کپی شد!");
    }).catch(function() {
      fallbackCopy(CONFIG.subject);
    });
  } else {
    fallbackCopy(CONFIG.subject);
  }
}

// روش قدیمی برای مرورگرهای قدیمی
function fallbackCopy(text) {
  var textarea = document.createElement("textarea");
  textarea.value = text;
  textarea.style.position = "fixed";
  textarea.style.opacity = "0";
  document.body.appendChild(textarea);
  textarea.select();
  try {
    document.execCommand("copy");
    showToast("✅ کپی شد!");
  } catch (e) {
    alert("❌ مرورگر شما از کپی خودکار پشتیبانی نمی‌کند. لطفاً متن را دستی انتخاب کنید.");
  }
  document.body.removeChild(textarea);
}
// نمایش پیام کوتاه (Toast)
function showToast(message) {
  var toast = document.createElement("div");
  toast.textContent = message;
  toast.style.cssText = [
    "position: fixed",
    "bottom: 30px",
    "left: 50%",
    "transform: translateX(-50%)",
    "background: #4caf50",
    "color: white",
    "padding: 12px 24px",
    "border-radius: 30px",
    "font-size: 14px",
    "z-index: 9999",
    "box-shadow: 0 8px 20px rgba(0,0,0,0.3)",
    "font-family: Tahoma"
  ].join(";");
  document.body.appendChild(toast);
  setTimeout(function() {
    toast.remove();
  }, 2500);
}

// باز کردن mailto
function sendReport() {
  var link = buildMailtoLink();
  window.location.href = link;

  sentCount++;
  try {
    localStorage.setItem(SENT_KEY, String(sentCount));
  } catch (e) {}
  updateCounter();

  setTimeout(function() {
    alert("اگر ایمیل باز شد، لطفاً دکمه Send را بزنید.\nمتشکریم که به حفظ امنیت تلگرام کمک می‌کنید.");
  }, 1500);
}

document.addEventListener("DOMContentLoaded", function() {
  try {
    var saved = localStorage.getItem(SENT_KEY);
    if (saved) sentCount = parseInt(saved, 10) || 0;
  } catch (e) {}

  showPreview();
  updateCounter();

  var copyBtn = document.getElementById("copyBtn");
  if (copyBtn) copyBtn.addEventListener("click", copyFullText);

  var copySubjectBtn = document.getElementById("copySubjectBtn");
  if (copySubjectBtn) copySubjectBtn.addEventListener("click", copySubject);

  var reportBtn = document.getElementById("reportBtn");
  if (reportBtn) reportBtn.addEventListener("click", sendReport);
});